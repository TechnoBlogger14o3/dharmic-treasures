export const temples: NumberedTemple[] = rows.map((row, index) => ({ ...row, id: index + 1 }))

export function templesGrouped(): { state: string; stateHindi: string; temples: NumberedTemple[] }[] {
  const map = new Map<string, { stateHindi: string; temples: NumberedTemple[] }>()
  for (const temple of temples) {
    const group = map.get(temple.state)
    if (group) group.temples.push(temple)
    else map.set(temple.state, { stateHindi: temple.stateHindi, temples: [temple] })
  }
  return [...map.entries()]
    .map(([state, group]) => ({ state, stateHindi: group.stateHindi, temples: group.temples }))
    .sort((a, b) => a.state.localeCompare(b.state))
}
