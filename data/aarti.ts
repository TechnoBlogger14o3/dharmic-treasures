import type { AartiHymn, AartiStanza } from '../types.ts'

function hymn(
  id: number,
  fields: Omit<AartiHymn, 'id' | 'chapter_number'>,
): AartiHymn {
  return { id, chapter_number: id, ...fields }
}

function line(id: number, text: string, refrain = false): AartiStanza {
  return {
    id,
    text,
    transliteration: '',
    hindi_meaning: '',
    meaning: '',
    ...(refrain ? { refrain } : {}),
  }
}

